"""Generate the dashboard's data-only TypeScript declarations from Pydantic.

No JavaScript runtime, model inference or external packages are required. The
limited conversion fails on unknown JSON Schema constructs rather than silently
substituting an untyped contract.
"""
from __future__ import annotations

import argparse
import hashlib
import json
from pathlib import Path

from kusama.continuation import ContinuationRequest
from kusama.continuation_dispatch import DispatchRequest
from kusama.corpus import ContextClaim, CorpusReference, Device, Region
from kusama.dashboard import ContinuationCreate, ContinuationObservation
from kusama.inspiration import ConnectionHypothesis, RenderAction
from kusama.reviews import Advancement, PoolChoice, Presentation, Vote


MODELS = (ContinuationRequest, DispatchRequest, ContinuationCreate, ContinuationObservation,
          ContextClaim, CorpusReference, Device, Region, ConnectionHypothesis,
          RenderAction, Advancement, PoolChoice, Presentation, Vote)
OUTPUT = Path(__file__).resolve().parents[1] / 'src/kusama/dashboard_static/contracts.d.ts'


def ts_type(schema):
    if '$ref' in schema:
        return schema['$ref'].rsplit('/', 1)[1]
    if 'const' in schema:
        return json.dumps(schema['const'])
    if 'enum' in schema:
        return ' | '.join(json.dumps(value) for value in schema['enum'])
    for union in ('anyOf', 'oneOf'):
        if union in schema:
            return ' | '.join(ts_type(value) for value in schema[union])
    kind = schema.get('type')
    if kind == 'array':
        if 'prefixItems' in schema:
            return '[' + ', '.join(ts_type(value) for value in schema['prefixItems']) + ']'
        return 'Array<' + ts_type(schema.get('items', {})) + '>'
    if kind == 'object' or 'properties' in schema:
        properties = schema.get('properties', {})
        additional = schema.get('additionalProperties', True)
        if not properties:
            return 'Record<string, ' + (ts_type(additional) if isinstance(additional, dict) else 'unknown') + '>'
        required = set(schema.get('required', []))
        lines = [f'  {json.dumps(key)}{"" if key in required else "?"}: {ts_type(value)};'
                 for key, value in properties.items()]
        if additional is not False:
            lines.append('  [key: string]: ' + (ts_type(additional) if isinstance(additional, dict) else 'unknown') + ';')
        return '{\n' + '\n'.join(lines) + '\n}'
    if kind in ('string', 'number', 'integer', 'boolean', 'null'):
        return {'integer': 'number'}.get(kind, kind)
    if not schema:
        return 'unknown'
    raise ValueError('Unsupported JSON Schema type: ' + json.dumps(schema))


def render():
    definitions = {}
    for model in MODELS:
        schema = model.model_json_schema()
        nested = schema.pop('$defs', {})
        for name, value in nested.items():
            if name in definitions and definitions[name] != value:
                raise ValueError('Conflicting Pydantic definition: ' + name)
            definitions[name] = value
        if model.__name__ in definitions and definitions[model.__name__] != schema:
            raise ValueError('Conflicting root Pydantic definition: ' + model.__name__)
        definitions[model.__name__] = schema
    fingerprint = hashlib.sha256(json.dumps(definitions, sort_keys=True).encode()).hexdigest()
    header = '// Generated by scripts/generate_contract_types.py; do not edit by hand.\n'
    header += '// JSON Schema SHA-256: ' + fingerprint + '\n'
    header += '// Runtime constraints (hashes, bounds, budgets, provenance) remain enforced by Pydantic and the server.\n\n'
    return header + '\n\n'.join('export type ' + name + ' = ' + ts_type(schema) + ';'
                                 for name, schema in sorted(definitions.items())) + '\n'


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true', help='Fail if checked-in declarations differ from the current Python schemas')
    args = parser.parse_args(argv)
    content = render()
    if args.check:
        if not OUTPUT.exists() or OUTPUT.read_text() != content:
            parser.exit(1, 'Generated TypeScript contracts differ; run this script without --check.\n')
        print('TypeScript contracts match the Pydantic schemas.')
    else:
        OUTPUT.write_text(content)
        print(OUTPUT)


if __name__ == '__main__':
    main()
